def _advance_date(d, freq):
    if freq == "monthly":
        return d + timedelta(days=30)
    if freq == "quarterly":
        return d + timedelta(days=90)
    if freq == "half_yearly":
        return d + timedelta(days=180)
    if freq == "annual":
        return d + timedelta(days=365)
    return d + timedelta(days=30)


