    # prevent duplicate: if an invoice already generated for this schedule+period, skip
    client = db.get(Client, sched.client_id)
    client_name = client.trade_name or client.legal_name if client else None
    items = [{"description": sched.description or "Recurring fee", "unit_price": sched.fee, "sac_code": sched.sac_code or "9982", "quantity": 1, "is_taxable": True}]
    from app.services.billing import create_invoice_record
    invoice = create_invoice_record(
        db,
        tenant_id=tenant_id,
        client_id=str(sched.client_id),
        items=items,
        due_days=15,
        invoice_date=sched.next_billing_date.isoformat() if sched.next_billing_date else None,
        created_by_id=principal.id,
    )
    db.add(invoice)
    # advance next billing date
    sched.next_billing_date = _advance_date(sched.next_billing_date or _dt.utcnow(), sched.frequency)
    db.commit()
    db.refresh(invoice)
    return {"invoice_id": str(invoice.id), "invoice_number": invoice.invoice_number, "next_billing_date": sched.next_billing_date.isoformat()}


