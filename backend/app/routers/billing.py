@router.patch("/invoices/{invoice_id}")
@router.patch("/billing/invoices/{invoice_id}", name="invoices-update-alias")
async def update_invoice(
    request: Request,
    invoice_id: str,
    db: Session = Depends(get_db),
    principal: Any = Depends(require_permission("invoice.write")),
) -> Any:
    """Update an existing draft invoice's fields.

    Allows patching client_id, invoice_date, due_date, lines, notes and terms
    on a draft invoice so the user can correct mistakes before issuing.  If
    ``issue`` is sent as ``true`` in the body the invoice is issued in the same
    request.
    """
    body = await request.json()

    invoice = db.get(Invoice, invoice_id)
    if invoice is None or str(invoice.tenant_id) != str(principal.tenant_id):
        raise NotFoundError(f"Invoice {invoice_id} not found")

    # Only drafts can be edited — once issued the copy may have been sent.
    if invoice.status != "draft":
        raise ValidationError(
            "Issued invoices cannot be edited. Cancel this invoice and create a new one."
        )

    if "client_id" in body and body["client_id"]:
        invoice.client_id = body["client_id"]
        client = db.get(Client, body["client_id"])
        if client and str(client.tenant_id) == str(principal.tenant_id):
            invoice.client_name = client.legal_name
            invoice.client_code = client.client_code

    if "invoice_date" in body and body["invoice_date"]:
        invoice.invoice_date = datetime.fromisoformat(body["invoice_date"].replace("Z", "+00:00"))

    if "due_date" in body and body["due_date"]:
        invoice.due_date = datetime.fromisoformat(body["due_date"].replace("Z", "+00:00"))

    if "notes" in body:
        invoice.notes = body["notes"]

    if "terms" in body:
        invoice.terms = body["terms"]

    if "tax_rate" in body and body["tax_rate"] is not None:
        invoice.tax_rate = float(body["tax_rate"])

    if "bank_details" in body:
        invoice.bank_details = body["bank_details"]

    # Rebuild line items from the payload.
    if "lines" in body and body["lines"]:
        new_lines = body["lines"]
        # Clear existing lines and recreate.
        for l in list(invoice.lines):
            db.delete(l)
        db.flush()
        for idx, ln in enumerate(new_lines, start=1):
            line = InvoiceLine(
                invoice_id=invoice.id,
                sequence=idx,
                description=ln.get("description", ""),
                sac_code=ln.get("sac_code"),
                service_id=ln.get("service_id"),
                task_id=ln.get("task_id"),
                quantity=int(ln.get("quantity", 1) or 1),
                unit_price=float(ln.get("unit_price", 0)),
                discount=float(ln.get("discount", 0) or 0),
                amount=float(ln.get("amount", 0)),
                is_taxable=bool(ln.get("is_taxable", True)),
            )
            db.add(line)

    db.commit()
    db.refresh(invoice)

    # Issue if requested.
    if body.get("issue"):
        invoice = issue_invoice(db, principal.tenant_id, str(invoice.id))

    return _build_invoice_detail(db, principal.tenant_id, invoice)


@router.get("/billing/receivables", name="billing-receivables", operation_id="get_billing_receivables")
async def get_receivables(
    request: Request,
    db: Session = Depends(get_db),
) -> Any:
    principal = await get_current_user(request, db)
    tenant_id = principal.tenant_id

    today = today_local()

    draft_rows = db.execute(
        select(Invoice).where(Invoice.tenant_id == tenant_id, Invoice.status == "draft")
    ).scalars().all()
    cancelled_rows = db.execute(
        select(Invoice).where(Invoice.tenant_id == tenant_id, Invoice.status == "cancelled")
    ).scalars().all()

    stmt = select(Invoice).where(
        Invoice.tenant_id == tenant_id,
        Invoice.status.in_(["issued", "partially_paid"]),
        Invoice.amount_paid < Invoice.total,
    )
    rows = db.execute(stmt).scalars().all()

    outstanding_total = 0.0
    invoiced_total = 0.0
    overdue_total = 0.0
    by_bucket: dict[str, float] = {}
    by_bucket_count: dict[str, int] = {}
    by_client_map: dict = {}

    for row in rows:
        outstanding = float(row.total) - float(row.amount_paid)
        invoiced_total += float(row.total)
        outstanding_total += outstanding
        due = row.due_date.date() if row.due_date else None
        days_overdue = (today - due).days if due else 0
        if days_overdue > 0:
            overdue_total += outstanding

        if days_overdue <= 0:
            bucket = "current"
        elif days_overdue <= 30:
            bucket = "1-30"
        elif days_overdue <= 60:
            bucket = "31-60"
        elif days_overdue <= 90:
            bucket = "61-90"
        else:
            bucket = "90+"
        by_bucket[bucket] = by_bucket.get(bucket, 0.0) + outstanding
        by_bucket_count[bucket] = by_bucket_count.get(bucket, 0) + 1

        cid = str(row.client_id) if row.client_id else None
        c = by_client_map.setdefault(cid, {
            "client_id": cid,
            "client_name": row.client_name or row.client_code or None,
            "client_code": row.client_code,
            "invoice_count": 0,
            "billed": 0.0,
            "collected": 0.0,
            "outstanding": 0.0,
            "overdue_outstanding": 0.0,
            "oldest_due_date": row.due_date,
            "worst_days_overdue": 0,
        })
        c["invoice_count"] += 1
        c["billed"] += float(row.total)
        c["collected"] += float(row.amount_paid)
        c["outstanding"] += outstanding
        if days_overdue > 0:
            c["overdue_outstanding"] += outstanding
        if row.due_date is not None:
            if c["oldest_due_date"] is None or row.due_date < c["oldest_due_date"]:
                c["oldest_due_date"] = row.due_date
        if days_overdue > c["worst_days_overdue"]:
            c["worst_days_overdue"] = days_overdue

    by_client = []
    for c in by_client_map.values():
        by_client.append({
            "client_id": c["client_id"],
            "client_name": c["client_name"],
            "client_code": c["client_code"],
            "invoice_count": c["invoice_count"],
            "billed": round(c["billed"], 2),
            "collected": round(c["collected"], 2),
            "outstanding": round(c["outstanding"], 2),
            "overdue_outstanding": round(c["overdue_outstanding"], 2),
            "oldest_due_date": c["oldest_due_date"].isoformat() if c["oldest_due_date"] else None,
            "worst_days_overdue": c["worst_days_overdue"],
        })

    collected_stmt = select(func.coalesce(func.sum(Payment.amount), 0)).select_from(Payment).join(Invoice).where(
        Invoice.tenant_id == tenant_id, Payment.paid_on >= today.replace(day=1)
    )
    collected_total = db.execute(collected_stmt).scalar() or 0.0

    oldest_overdue = None
    oldest_days = 0
    for r in rows:
        due = r.due_date.date() if r.due_date else None
        days_overdue = (today - due).days if due else 0
        if days_overdue > 0 and days_overdue > oldest_days:
            oldest_days = days_overdue
            oldest_overdue = r

    oldest_overdue_row = None
    if oldest_overdue is not None:
        oldest_overdue_row = {
            "invoice_id": str(oldest_overdue.id),
            "invoice_number": oldest_overdue.invoice_number,
            "client_id": str(oldest_overdue.client_id) if oldest_overdue.client_id else None,
            "client_name": oldest_overdue.client_name or oldest_overdue.client_code or None,
            "client_code": oldest_overdue.client_code,
            "status": oldest_overdue.status,
            "invoice_date": oldest_overdue.invoice_date.isoformat() if oldest_overdue.invoice_date else None,
            "due_date": oldest_overdue.due_date.isoformat() if oldest_overdue.due_date else None,
            "total": round(float(oldest_overdue.total), 2),
            "amount_paid": round(float(oldest_overdue.amount_paid), 2),
            "outstanding": round(float(oldest_overdue.total) - float(oldest_overdue.amount_paid), 2),
            "days_overdue": oldest_days,
            "ageing_bucket": oldest_overdue.ageing_bucket if oldest_overdue.ageing_bucket else "current",
            "is_overdue": True,
        }

    return {
        "as_of": today.isoformat(),
        "invoiced_total": round(invoiced_total, 2),
        "collected_total": round(float(collected_total), 2),
        "outstanding_total": round(outstanding_total, 2),
        "overdue_total": round(overdue_total, 2),
        "overdue_count": sum(1 for r in rows if (float(r.total) - float(r.amount_paid)) > 0 and r.due_date and r.due_date.date() < today),
        "draft_count": len(draft_rows),
        "draft_value": round(sum(float(r.total) for r in draft_rows), 2),
        "cancelled_count": len(cancelled_rows),
        "ageing": {k: round(v, 2) for k, v in by_bucket.items()},
        "ageing_counts": {k: v for k, v in by_bucket_count.items()},
        "by_client": by_client,
        "oldest_overdue": oldest_overdue_row,
        "recent": [],
        "notes": [],
    }


