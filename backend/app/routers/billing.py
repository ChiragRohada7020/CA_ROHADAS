@router.get("/billing/reports/outstanding")
async def outstanding_report(request: Request, db: Session = Depends(get_db)) -> Any:
    principal = await get_current_user(request, db)
    tenant_id = principal.tenant_id
    rows = db.execute(select(Invoice).where(Invoice.tenant_id == tenant_id, Invoice.amount_paid < Invoice.total)).scalars().all()
    data = []
    for r in rows:
        data.append({
            "invoice_id": str(r.id),
            "invoice_number": r.invoice_number,
            "client_name": r.client_name,
            "total": r.total,
            "amount_paid": r.amount_paid,
            "outstanding": r.outstanding,
            "due_date": r.due_date.isoformat() if r.due_date else None,
        })
    return {"items": data, "total_outstanding": round(sum(float(x["outstanding"]) for x in data), 2)}
